## Laravel Doctrine Factory

This package provides Laravel's modern Eloquent factory API (`make()`, `create()`, 
`state()`, `has()`, `for()`, sequences, callbacks, etc.) for Doctrine ORM entities. 
Extend `Stemble\LaravelDoctrineFactory\DoctrineFactory` instead of Laravel's `Factory` 
and add the standard `HasFactory` trait to your entity.

When writing tests or factories for Doctrine entities, use the `laravel-doctrine-factory` 
skill for detailed guidance.
